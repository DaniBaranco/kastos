const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** "25 años y 3 meses", "8 meses"… */
export function durationLabel(months: number): string {
  const y = Math.floor(months / 12);
  const m = months % 12;
  const parts: string[] = [];
  if (y > 0) parts.push(`${y} ${plural(y, 'año', 'años')}`);
  if (m > 0 || y === 0) parts.push(`${m} ${plural(m, 'mes', 'meses')}`);
  return parts.join(' y ');
}

